nginx_add_site() {
  local domain root conf body
  domain="$(prompt_value "Domena/site name")"
  [ -n "$domain" ] || return 0
  root="/var/www/$domain/public"
  conf="/etc/nginx/sites-available/$domain"
  body=$(cat <<EOF
server {
    listen 80;
    listen [::]:80;
    server_name $domain;
    root $root;
    index index.html index.htm;

    location / {
        try_files \$uri \$uri/ =404;
    }
}
EOF
)
  ui_begin "NGINX new site"
  info "Kreiram $root i $conf"
  confirm "Nastaviti?" || return 0
  log_comment "Create NGINX site $domain"
  log_action "sudo mkdir -p $root"
  run_root mkdir -p "$root"
  printf '<h1>%s</h1>\n' "$domain" | run_root tee "$root/index.html" >/dev/null
  [ -e "$conf" ] && backup_file "$conf"
  printf '%s\n' "$body" | run_root tee "$conf" >/dev/null
  log_write_file "$root/index.html" "<h1>$domain</h1>"
  log_write_file "$conf" "$body"
  log_action "sudo ln -sfn $conf /etc/nginx/sites-enabled/$domain"
  run_root ln -sfn "$conf" "/etc/nginx/sites-enabled/$domain"
  run_root nginx -t && service_restart nginx
  pause
}

