  if [ -r /etc/os-release ]; then
    # shellcheck disable=SC1091
    . /etc/os-release
    case "${ID:-}" in
      ubuntu|debian) return 0 ;;
      *) warn "Detektiran je ${PRETTY_NAME:-nepoznat OS}. Alat je ciljan za Ubuntu/Debian." ;;
    esac
  fi
}

ssh_config_file() {
  [ -f /etc/ssh/sshd_config ] && printf '%s\n' /etc/ssh/sshd_config || printf '%s\n' /etc/ssh/ssh_config
}

ssh_main_setting() {
  local key="$1" default="$2" cfg value
  cfg="$(ssh_config_file)"
  value="$(awk -v k="$key" -v d="$default" '
    BEGIN {IGNORECASE=1}
    /^[[:space:]]*Match[[:space:]]/ {exit}
    /^[[:space:]]*#/ {next}
    tolower($1)==tolower(k) {val=$2}
    END {print val ? val : d}
  ' "$cfg")"
  printf '%s\n' "$value"
}

ssh_root_login_state() {
  ssh_main_setting "PermitRootLogin" "yes"
}

ssh_password_auth_state() {
  ssh_main_setting "PasswordAuthentication" "yes"
}

has_non_root_shell_user() {
  awk -F: '$1 != "root" && $7 !~ /(nologin|false)$/ {found=1} END {exit found ? 0 : 1}' /etc/passwd
}

has_sudo_user() {
  getent group sudo 2>/dev/null | awk -F: 'NF >= 4 && $4 != "" {print "yes"}' | grep -q '^yes$'
}

ufw_is_active() {
  command -v ufw >/dev/null 2>&1 && ufw status 2>/dev/null | head -n 1 | grep -qi 'Status: active'
}

ufw_status_output() {
  command -v ufw >/dev/null 2>&1 || return 1
  ufw status verbose 2>/dev/null || true
}

ufw_default_is_good() {
  local direction="$1" expected="$2" line
  line="$(ufw_status_output | grep -i '^Default:' || true)"
  printf '%s\n' "$line" | grep -Eiq "${expected}[[:space:]]+\(${direction}\)"
}

ufw_rule_allows() {
  local port="$1"
  command -v ufw >/dev/null 2>&1 || return 1
  ufw status 2>/dev/null | grep -Eiq "^${port}(/tcp)?[[:space:]]+ALLOW"
}

ufw_status_panel() {
  local status default_line rules
  if ! command -v ufw >/dev/null 2>&1; then
    printf '%bInstalled:%b no\n' "$C_RED$C_BOLD" "$C_RESET"
    printf '%bProblem:%b UFW nije instaliran. Firewall baseline se ne moze primijeniti.\n' "$C_RED" "$C_RESET"
    printf '%bPrijedlog:%b instaliraj UFW i primijeni baseline prije izlaganja servisa javnom internetu.\n' "$C_YELLOW" "$C_RESET"
    return 0
  fi

  status="$(ufw status 2>/dev/null | head -n 1 || true)"
  default_line="$(ufw_status_output | grep -i '^Default:' || true)"
  rules="$(ufw status 2>/dev/null | sed '1,4d' || true)"

  printf '%bInstalled:%b yes (%s)\n' "$C_GREEN" "$C_RESET" "$(package_version ufw)"
  if printf '%s\n' "$status" | grep -qi 'active'; then
    printf '%bStatus:%b active\n' "$C_GREEN" "$C_RESET"
  else
    printf '%bStatus:%b inactive\n' "$C_RED$C_BOLD" "$C_RESET"
  fi

  if [ -n "$default_line" ]; then
    if ufw_default_is_good "incoming" "deny"; then
      printf '%bDefault incoming:%b deny\n' "$C_GREEN" "$C_RESET"
    else
      printf '%bDefault incoming:%b %s\n' "$C_RED$C_BOLD" "$C_RESET" "$default_line"
    fi
    if ufw_default_is_good "outgoing" "allow"; then
      printf '%bDefault outgoing:%b allow\n' "$C_GREEN" "$C_RESET"
    else
      printf '%bDefault outgoing:%b %s\n' "$C_RED$C_BOLD" "$C_RESET" "$default_line"
    fi
  else
    printf '%bDefault policies:%b nije moguce procitati bez dodatnih prava ili UFW nije inicijaliziran.\n' "$C_YELLOW" "$C_RESET"
  fi

  printf '\n%bOsnovna pravila:%b\n' "$C_CYAN" "$C_RESET"
  for port in 22 80 443; do
    if ufw_rule_allows "$port"; then
      printf '  %bALLOW %s/tcp%b\n' "$C_GREEN" "$port" "$C_RESET"
    else
      printf '  %bMISSING allow %s/tcp%b\n' "$C_RED$C_BOLD" "$port" "$C_RESET"
    fi
  done

  printf '\n%bPostojeca UFW pravila:%b\n' "$C_CYAN" "$C_RESET"
  if [ -n "$rules" ]; then
    printf '%s\n' "$rules" | sed '/^[[:space:]]*$/d' | head -n 12
  else
    printf '  - nema pravila ili ih nije moguce procitati\n'
  fi

  printf '\n%bPrijedlozi:%b\n' "$C_YELLOW" "$C_RESET"
  printf '%s\n' "$status" | grep -qi 'active' || printf '  - Enable UFW nakon sto je SSH port dozvoljen, inace mozes izgubiti pristup.\n'
  ufw_default_is_good "incoming" "deny" || printf '  - Postavi default deny incoming.\n'
  ufw_default_is_good "outgoing" "allow" || printf '  - Postavi default allow outgoing.\n'
  ufw_rule_allows 22 || printf '  - Dozvoli 22/tcp prije enable koraka ako SSH koristis za pristup serveru.\n'
  ufw_rule_allows 80 || printf '  - Dozvoli 80/tcp ako server treba HTTP.\n'
  ufw_rule_allows 443 || printf '  - Dozvoli 443/tcp ako server treba HTTPS.\n'
}

nginx_is_installed() {
  dpkg-query -W -f='${Status}' nginx 2>/dev/null | grep -q "install ok installed"
}

backup_jobs_count() {
  find /etc/cron.d -maxdepth 1 -type f -name 'ubuntuav-*' 2>/dev/null | wc -l | tr -d ' '
}

security_recommendation_count() {
  local count=0
  [ "$(ssh_root_login_state)" != "no" ] && count=$((count + 1))
  [ "$(ssh_password_auth_state)" = "yes" ] && count=$((count + 1))
  ufw_is_active || count=$((count + 1))
  printf '%s\n' "$count"
}

web_recommendation_count() {
  local count=0
  if nginx_is_installed && [ ! -f /etc/nginx/snippets/ubuntuav-rate-limit-location.conf ]; then
    count=$((count + 1))
  fi
  printf '%s\n' "$count"
}

operations_recommendation_count() {
  local count=0
  [ "$(backup_jobs_count)" -eq 0 ] && count=$((count + 1))
  printf '%s\n' "$count"
}

ssh_recommendations() {
  local root_state pass_state
  root_state="$(ssh_root_login_state)"
  pass_state="$(ssh_password_auth_state)"
  printf '%bStatus:%b PermitRootLogin=%s | PasswordAuthentication=%s\n' "$C_CYAN" "$C_RESET" "$root_state" "$pass_state"
  if has_non_root_shell_user; then
    printf '%bCheck:%b postoji barem jedan non-root shell user.\n' "$C_GREEN" "$C_RESET"
  else
    printf '%bRisk:%b ne postoji nijedan non-root shell user. Ne gasi root login dok ne kreiras admin user.\n' "$C_RED" "$C_RESET"
  fi
  if has_sudo_user; then
    printf '%bCheck:%b postoji barem jedan sudo korisnik.\n' "$C_GREEN" "$C_RESET"
  else
    printf '%bRisk:%b sudo grupa nema korisnika. Prvo osiguraj admin pristup prije hardeninga.\n' "$C_RED" "$C_RESET"
  fi
  [ "$root_state" = "no" ] || printf '%bBest practice:%b ugasi root remote login nakon sto potvrdis alternativni admin pristup.\n' "$C_YELLOW" "$C_RESET"
  [ "$pass_state" != "yes" ] || printf '%bBest practice:%b ugasi globalni password auth ili ga ograniciti samo na trusted mreze.\n' "$C_YELLOW" "$C_RESET"
}

backup_file() {
  local file="$1"
  if [ ! -e "$file" ]; then
    warn "Datoteka ne postoji, backup preskocen: $file"
    return 0
  fi
  local dir base dest
  dir="$(dirname "$file")"
  base="$(basename "$file")"
  dest="$dir/$(timestamp).$base"
  run_root cp -a "$file" "$dest"
  info "Backup: $dest"
}

safe_append_once() {
  local file="$1" marker="$2" content="$3"
  if [ -f "$file" ] && grep -Fq "$marker" "$file"; then
    info "Blok vec postoji u $file"
    return 0
  fi
  backup_file "$file"
  printf '%s\n' "$content" | run_root tee -a "$file" >/dev/null
  log_comment "Append managed block to $file"
  log_append_file "$file" "$content"
}

download_file() {
  local url="$1" output="$2"
  if command -v curl >/dev/null 2>&1; then
    curl -fsSL -o "$output" "$url"
  elif command -v wget >/dev/null 2>&1; then
    wget -O "$output" "$url"
  else
    err "Ni curl ni wget nisu dostupni za download."
    return 1
  fi
}

install_packages() {
  local packages=("$@")
  [ "${#packages[@]}" -eq 0 ] && return 0
  info "Paketi za instalaciju: ${packages[*]}"
  confirm "Instalirati apt pakete?" || return 0
  log_comment "Install packages: ${packages[*]}"
  log_action "sudo apt-get update"
  log_action "sudo apt-get install -y ${packages[*]}"
  run_root apt-get update
  run_root apt-get install -y "${packages[@]}"
}

service_restart() {
  local svc="$1"
  if confirm "Restartati servis $svc?"; then
    log_comment "Restart service $svc"
    log_action "sudo systemctl restart $svc"
    run_root systemctl restart "$svc"
  fi
}

print_cmd() {
  local title="$1"
  shift
  printf '%b%s%b\n' "$C_BOLD$C_WHITE" "$title" "$C_RESET"
  if "$@"; then :; else warn "Naredba nije uspjela: $*"; fi
  printf '\n'
}

main_menu() {
  while true; do
    local choice overview_item security_item web_item data_item ops_item
    overview_item="$(menu_badge "Pregled i inventar" 0)"
    security_item="$(menu_badge "Pristup i sigurnost" "$(security_recommendation_count)")"
    web_item="$(menu_badge "Web stack" "$(web_recommendation_count)")"
    data_item="$(menu_badge "Baze i runtime" 0)"
    ops_item="$(menu_badge "Operacije i backup" "$(operations_recommendation_count)")"
    choice="$(menu_select "Glavni izbornik" \
      "$overview_item" \
      "$security_item" \
      "$web_item" \
      "$data_item" \
      "$ops_item" \
      "GitHub deploy helper" \
      "Backups list / restore" \
      "Exit")"
    case "$choice" in
      0) menu_overview ;;
      1) menu_security ;;
      2) menu_web_stack ;;
      3) menu_data_runtime ;;
      4) menu_operations ;;
      5) menu_github_deploy ;;
      6) menu_backups ;;
      7) exit 0 ;;
    esac
  done
}

