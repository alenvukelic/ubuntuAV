ssh_audit() {
  local cfg
  cfg="$(ssh_config_file)"
  printf 'Config: %s\n' "$cfg"
  grep -Ei '^(PermitRootLogin|PasswordAuthentication|KbdInteractiveAuthentication|PubkeyAuthentication|AllowUsers|Match)' "$cfg" || true
  printf '\nKorisnici s shell pristupom:\n'
  awk -F: '$7 !~ /(nologin|false)$/ {print $1 " -> " $7}' /etc/passwd
  printf '\nAuthorized keys:\n'
  find /home /root -maxdepth 3 -name authorized_keys -type f -printf '%p\n' 2>/dev/null || true
}

ssh_disable_root_login() {
  ui_begin "SSH root login hardening"
  ssh_audit
  printf '\n'
  ssh_recommendations
  if ! has_non_root_shell_user; then
    err "Nema non-root shell usera. Prvo kreiraj admin korisnika."
    pause
    return 1
  fi
  if ! has_sudo_user; then
    err "Nema korisnika u sudo grupi. Prvo osiguraj admin pristup."
    pause
    return 1
  fi
  ssh_set_option PermitRootLogin no
}

ssh_set_option() {
  local key="$1" val="$2" cfg
  cfg="$(ssh_config_file)"
  ui_begin "SSH konfiguracija"
  ssh_audit
  confirm "Postaviti $key $val u $cfg?" || return 0
  backup_file "$cfg"
  if grep -Eq "^[#[:space:]]*$key[[:space:]]+" "$cfg"; then
    log_comment "Set $key $val in $cfg"
    log_action "sudo sed -i -E 's|^[#[:space:]]*$key[[:space:]]+.*|$key $val|' $cfg"
    run_root sed -i -E "s|^[#[:space:]]*$key[[:space:]]+.*|$key $val|" "$cfg"
  else
    log_comment "Append $key $val to $cfg"
    log_action "printf '%s %s\\n' '$key' '$val' | sudo tee -a $cfg >/dev/null"
    printf '%s %s\n' "$key" "$val" | run_root tee -a "$cfg" >/dev/null
  fi
  run_root sshd -t
  pause
}

